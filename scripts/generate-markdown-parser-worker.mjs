import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const workspaceRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(
  workspaceRoot,
  "packages/markweave/src/editor-core/markdown-parser-worker-entry.ts",
);
const generatedFile = resolve(
  workspaceRoot,
  "packages/markweave/src/editor-core/markdown-parser-worker-source.generated.ts",
);

const result = await build({
  configFile: false,
  logLevel: "warn",
  build: {
    emptyOutDir: false,
    lib: {
      entry,
      fileName: () => "markdown-parser-worker.js",
      formats: ["iife"],
      name: "MarkweaveMarkdownParserWorker",
    },
    minify: true,
    target: "es2019",
    write: false,
  },
});

const chunks = (Array.isArray(result) ? result : [result])
  .flatMap((buildResult) => buildResult.output)
  .filter((output) => output.type === "chunk");
if (chunks.length !== 1) {
  throw new Error(`Expected one Markdown parser worker chunk, received ${chunks.length}.`);
}

const source = chunks[0].code;
const moduleSource = [
  "// Generated by scripts/generate-markdown-parser-worker.mjs. Do not edit manually.",
  `export const markweaveMarkdownParserWorkerSource = ${JSON.stringify(source)};`,
  "",
].join("\n");

await mkdir(dirname(generatedFile), { recursive: true });
await writeFile(generatedFile, moduleSource, "utf8");

const generated = await readFile(generatedFile, "utf8");
process.stdout.write(
  `[Markweave Markdown Worker] generated ${Buffer.byteLength(generated)} bytes.\n`,
);
